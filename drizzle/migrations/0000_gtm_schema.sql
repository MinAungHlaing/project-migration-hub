
-- Roles
create type public.app_role as enum ('admin');
create table public.user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade not null,
  role app_role not null,
  unique (user_id, role)
);
grant select on public.user_roles to authenticated;
grant all on public.user_roles to service_role;
alter table public.user_roles enable row level security;
create policy "own roles readable" on public.user_roles for select to authenticated using (user_id = auth.uid());

create or replace function public.has_role(_user_id uuid, _role app_role)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.user_roles where user_id = _user_id and role = _role)
$$;

-- First account ever created becomes the admin (replaces the old single env-configured admin login)
create or replace function public.grant_first_admin()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.user_roles where role = 'admin') then
    insert into public.user_roles (user_id, role) values (new.id, 'admin');
  end if;
  return new;
end $$;
create trigger on_auth_user_first_admin after insert on auth.users
  for each row execute function public.grant_first_admin();

-- Catalog
create table public.products (
  id bigint generated by default as identity primary key,
  product_id text not null default '',
  product_name text not null default '',
  upc bigint not null default 0,
  unit text not null default '-',
  retail numeric not null default 0,
  wholesale numeric not null default 0,
  category text not null default 'General',
  status text not null default 'In Stock',
  description text not null default '',
  supplier text not null default '',
  base_price numeric,
  b2c numeric,
  retail_pct numeric,
  wholesale_pct numeric,
  b2c_pct numeric,
  has_image boolean not null default false,
  image_path text,
  generation int not null default 1,
  updated_at timestamptz not null default now()
);
create unique index products_product_id_norm on public.products (replace(lower(product_id), ' ', '')) where trim(product_id) <> '';

create table public.price_history (
  id bigint generated by default as identity primary key,
  product_id text not null,
  generation int not null default 1,
  product_name text not null default '',
  old_retail numeric, new_retail numeric,
  old_wholesale numeric, new_wholesale numeric,
  old_base_price numeric, new_base_price numeric,
  old_b2c numeric, new_b2c numeric,
  changed_at timestamptz not null default now(),
  source text not null default 'manual'
);
create index on public.price_history (product_id, generation);

create table public.activity_log (
  id bigint generated by default as identity primary key,
  event_type text not null,
  product_id text not null,
  generation int not null default 1,
  product_name text not null default '',
  details text not null default '',
  source text not null default 'manual',
  created_at timestamptz not null default now()
);
create index on public.activity_log (created_at desc);
create index on public.activity_log (product_id, generation);

create table public.id_counter (id int primary key check (id = 1), next_number int not null);

