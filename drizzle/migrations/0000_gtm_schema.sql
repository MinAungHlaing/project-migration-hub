-- Grants: service_role everywhere; admin access via RLS for authenticated
do $$
declare t text;
begin
  foreach t in array array['products','price_history','activity_log','id_counter','sales_reps','outlets','outlet_aliases','orders','order_items','outlet_visits','catalog_snapshots','delivery_assignments','delivery_attempts','delivery_attempt_items','delivery_handovers','delivery_handover_items','push_subscriptions','stock_balances','stock_movements','stock_counts','stock_count_lines','purchase_orders','purchase_order_items','rep_credentials']
  loop
    execute format('grant all on public.%I to service_role', t);
    execute format('alter table public.%I enable row level security', t);
    if t not in ('rep_credentials','catalog_snapshots','push_subscriptions','id_counter') then
      execute format('grant select, insert, update, delete on public.%I to authenticated', t);
      execute format('create policy "admins manage" on public.%I for all to authenticated using (public.has_role(auth.uid(), ''admin'')) with check (public.has_role(auth.uid(), ''admin''))', t);
    end if;
  end loop;
end $$;

